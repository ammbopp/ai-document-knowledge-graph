def t(key, lang=DEFAULT_LANG, **kwargs):
    """Look up a UI string; falls back to Thai, then to the key itself."""
    text = STRINGS.get(lang, {}).get(key) or STRINGS[DEFAULT_LANG].get(key, key)
    return text.format(**kwargs) if kwargs else text


def graph_labels(lang):
    keys = ["dark", "light", "freeze", "unfreeze", "overview", "connected", "no_connections", "no_context",
            "type", "connections", "implicit"]
    mapping = {"dark": "dark_mode", "light": "light_mode"}
    return {mapping.get(k, k): t("g_" + k, lang) for k in keys}


def type_names(lang):
    return {k: t(k, lang) for k in ("Person", "Organization", "Location", "Time", "Work", "Entity", "Topic")}
